ISSUER = "https://oidc.example.com"


def _openssl(*args):
    return subprocess.run(["openssl", *args], check=True, capture_output=True).stdout


def _b64url(data):
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode("ascii")


def _hex_field(text, name):
    """One integer from `openssl pkey -text`: a decimal value or a colon hex block."""

    match = re.search(rf"^{name}:[ \t]*(\d+)", text, re.MULTILINE)
    if match:
        return int(match.group(1))
    match = re.search(rf"^{name}:\s*\n((?:\s+[0-9a-f:]+\n)+)", text, re.MULTILINE)
    return int(re.sub(r"[^0-9a-f]", "", match.group(1)), 16)


class _Fixture:
    """A key generated by openssl and its values read back from openssl."""

    def __init__(self, directory, name, bits):
        self.pem_path = Path(directory) / f"{name}.pem"
        _openssl(
            "genpkey",
            "-algorithm",
            "RSA",
            "-pkeyopt",
            f"rsa_keygen_bits:{bits}",
            "-out",
            str(self.pem_path),
        )
        self.public_path = Path(directory) / f"{name}.pub"
        _openssl("pkey", "-in", str(self.pem_path), "-pubout", "-out", str(self.public_path))
        text = _openssl("pkey", "-in", str(self.pem_path), "-noout", "-text").decode("ascii")
        modulus = _hex_field(text, "modulus")
        exponent = _hex_field(text, "publicExponent")
        private = _hex_field(text, "privateExponent")
        self.n = _b64url(modulus.to_bytes((modulus.bit_length() + 7) // 8, "big"))
        self.e = _b64url(exponent.to_bytes((exponent.bit_length() + 7) // 8, "big"))
        self.d = _b64url(private.to_bytes((private.bit_length() + 7) // 8, "big"))
        # RFC 7638 section 3: the required members in lexicographic order, no whitespace.
        canonical = '{"e":"' + self.e + '","kty":"RSA","n":"' + self.n + '"}'
        self.kid = _b64url(hashlib.sha256(canonical.encode("ascii")).digest())


def _verifies(fixture, token):
    header, payload, signature = token.split(".")
    with tempfile.TemporaryDirectory(prefix="execution-oidc-verify-") as scratch:
        message = Path(scratch) / "message"
        message.write_bytes(f"{header}.{payload}".encode("ascii"))
        sig = Path(scratch) / "sig"
        sig.write_bytes(base64.urlsafe_b64decode(signature + "=" * (-len(signature) % 4)))
        result = subprocess.run(
            [
                "openssl",
                "dgst",
                "-sha256",
                "-verify",
                str(fixture.public_path),
                "-signature",
                str(sig),
                str(message),
            ],
            capture_output=True,
        )
    return result.returncode == 0


def _segment(token, index):
    part = token.split(".")[index]
    return json.loads(base64.urlsafe_b64decode(part + "=" * (-len(part) % 4)))


class OidcKeyTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.generated = tempfile.TemporaryDirectory(prefix="execution-oidc-keys-")
        cls.a = _Fixture(cls.generated.name, "a", 2048)
        cls.b = _Fixture(cls.generated.name, "b", 2048)
        cls.small = _Fixture(cls.generated.name, "small", 1024)

    @classmethod
    def tearDownClass(cls):
        cls.generated.cleanup()

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory(prefix="execution-test-")
        # /var is a symlink on macOS. A key path with a symlink component is refused.
        self.root = Path(self.tmp.name).resolve()
        self.key_dir = self.root / "keys"
        self.key_dir.mkdir(mode=0o700)
        os.chmod(self.key_dir, 0o700)
        self.oidc = self.key_dir / "oidc"
        self.oidc.mkdir(mode=0o700)
        os.chmod(self.oidc, 0o700)
        self.out = self.root / "site"

    def tearDown(self):
        self.tmp.cleanup()

    def _install(self, fixture, name=None):
        target = self.oidc / (name or f"{fixture.kid}.pem")
        shutil.copyfile(fixture.pem_path, target)
        os.chmod(target, 0o600)
        return target

    def _activate(self, kid):
        active = self.oidc / "active"
        active.write_text(kid + "\n")
        os.chmod(active, 0o600)

    def _refused(self, kind="OIDC_KEY_UNREADABLE"):
        with self.assertRaises(OidcError) as caught:
            load_key_set(str(self.key_dir))
        self.assertEqual(caught.exception.kind, kind)
        return str(caught.exception)

    def test_the_kid_is_the_rfc7638_thumbprint_of_the_public_key(self):
        self._install(self.a)
        self._activate(self.a.kid)
        key_set = load_key_set(str(self.key_dir))
        self.assertEqual(key_set.active.kid, self.a.kid)
        self.assertEqual(
            key_set.jwks(),
            {
                "keys": [
                    {
                        "kty": "RSA",
                        "use": "sig",
                        "alg": "RS256",
                        "kid": self.a.kid,
                        "e": self.a.e,
                        "n": self.a.n,
                    }
                ]
            },
        )

    def test_rotation_publishes_both_keys_and_only_the_active_key_signs(self):
        self._install(self.a)
        self._install(self.b)
        self._activate(self.a.kid)
        key_set = load_key_set(str(self.key_dir))
        self.assertEqual(
            sorted(key["kid"] for key in key_set.jwks()["keys"]), sorted([self.a.kid, self.b.kid])
        )
        token = key_set.sign_jwt({"aud": "sts.amazonaws.com"})
        self.assertEqual(_segment(token, 0), {"alg": "RS256", "typ": "JWT", "kid": self.a.kid})
        self.assertEqual(_segment(token, 1), {"aud": "sts.amazonaws.com"})
        self.assertTrue(_verifies(self.a, token))
        self.assertFalse(_verifies(self.b, token))

        self._activate(self.b.kid)
        switched = load_key_set(str(self.key_dir))
        token = switched.sign_jwt({"aud": "sts.amazonaws.com"})
        self.assertEqual(_segment(token, 0)["kid"], self.b.kid)
        self.assertTrue(_verifies(self.b, token))
        self.assertFalse(_verifies(self.a, token))
        self.assertEqual(
            sorted(key["kid"] for key in switched.jwks()["keys"]),
            sorted([self.a.kid, self.b.kid]),
        )

    def test_publish_refuses_when_the_active_key_has_no_file(self):
        self._install(self.b)
        self._activate(self.a.kid)
        message = self._refused("OIDC_ACTIVE_MISSING")
        self.assertIn(self.a.kid, message)
        with self.assertRaises(OidcError) as caught:
            OidcKeySet([OidcKey(*_load_rsa_key(self.b.pem_path.read_bytes()))], self.a.kid)
        self.assertEqual(caught.exception.kind, "OIDC_ACTIVE_MISSING")

        result = _run_cli(self.key_dir, self.out)
        self.assertEqual(result.returncode, 1)
        self.assertEqual(json.loads(result.stderr)["error"]["kind"], "OIDC_ACTIVE_MISSING")
        self.assertEqual(result.stdout, "")
        self.assertFalse(self.out.exists())

    def test_a_retired_key_is_gone_from_the_next_jwks(self):
        old = self._install(self.a)
        self._install(self.b)
        self._activate(self.b.kid)
        publish(load_key_set(str(self.key_dir)), ISSUER, self.out, str(self.key_dir))
        jwks_path = self.out / ".well-known" / "jwks.json"
        self.assertIn(self.a.n, jwks_path.read_text())

        old.unlink()
        publish(load_key_set(str(self.key_dir)), ISSUER, self.out, str(self.key_dir))
        written = json.loads(jwks_path.read_text())
        self.assertEqual([key["kid"] for key in written["keys"]], [self.b.kid])
        self.assertNotIn(self.a.n, jwks_path.read_text())

    def test_publish_writes_only_public_members_and_the_discovery_document(self):
        self._install(self.a)
        self._activate(self.a.kid)
        result = _run_cli(self.key_dir, self.out)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(
            json.loads(result.stdout),
            {
                "oidc": {
                    "issuer": ISSUER,
                    "active": self.a.kid,
                    "kids": [self.a.kid],
                    "files": [".well-known/openid-configuration", ".well-known/jwks.json"],
                }
            },
        )
        jwks_text = (self.out / ".well-known" / "jwks.json").read_text()
        self.assertNotIn(self.a.d, jwks_text)
        self.assertEqual(
            set(json.loads(jwks_text)["keys"][0]), {"kty", "use", "alg", "kid", "n", "e"}
        )
        discovery = json.loads((self.out / ".well-known" / "openid-configuration").read_text())
        self.assertEqual(discovery["issuer"], "https://oidc.example.com")
        self.assertEqual(discovery["jwks_uri"], "https://oidc.example.com/.well-known/jwks.json")
        self.assertEqual(discovery["id_token_signing_alg_values_supported"], ["RS256"])
        self.assertEqual(discovery["response_types_supported"], ["id_token"])
        self.assertEqual(discovery["subject_types_supported"], ["public"])
        self.assertIn("repository_id", discovery["claims_supported"])
        self.assertNotIn(".pem", "".join(path.name for path in self.out.rglob("*")))

    def test_an_output_directory_inside_the_key_directory_is_refused(self):
        self._install(self.a)
        self._activate(self.a.kid)
        inside = self.key_dir / "site"
        with self.assertRaises(OidcError) as caught:
            publish(load_key_set(str(self.key_dir)), ISSUER, inside, str(self.key_dir))
        self.assertEqual(caught.exception.kind, "INVALID_PARAMS")
        self.assertFalse(inside.exists())

    def test_a_symlinked_key_is_refused(self):
        target = self.root / "elsewhere.pem"
        shutil.copyfile(self.a.pem_path, target)
        os.chmod(target, 0o600)
        (self.oidc / f"{self.a.kid}.pem").symlink_to(target)
        self._activate(self.a.kid)
        self._refused()

    def test_a_world_readable_key_is_refused(self):
        os.chmod(self._install(self.a), 0o644)
        self._activate(self.a.kid)
        self._refused()

    def test_an_open_oidc_directory_is_refused(self):
        self._install(self.a)
        self._activate(self.a.kid)
        os.chmod(self.oidc, 0o755)
        self._refused()

    def test_a_readable_active_pointer_is_refused(self):
        self._install(self.a)
        self._activate(self.a.kid)
        os.chmod(self.oidc / "active", 0o644)
        self._refused()

    def test_a_file_not_named_for_its_kid_is_refused_with_the_kid(self):
        self._install(self.a, "next.pem")
        self._activate(self.a.kid)
        message = self._refused()
        self.assertIn(f"{self.a.kid}.pem", message)

    def test_a_key_below_2048_bits_is_refused(self):
        self._install(self.small)
        self._activate(self.small.kid)
        self.assertIn("2048", self._refused())

    def test_an_empty_oidc_directory_is_refused(self):
        self._activate(self.a.kid)
        self.assertIn("no key", self._refused())

    def test_issuer_urls(self):
        for good in (ISSUER, "https://example.com/oidc", "https://oidc.example.com:8443"):
            self.assertEqual(require_issuer(good), good)
        for bad in (
            "http://oidc.example.com",
            "https://oidc.example.com/",
            "https://oidc.example.com?x=1",
            "https://oidc.example.com#x",
            "https://user@oidc.example.com",
            "https://oidc.example.com:0",
            "https://oidc.example.com:99999",
            "https://",
            "https://oidc example.com",
            "oidc.example.com",
            "",
            None,
        ):
            with self.assertRaises(OidcError, msg=bad):
                require_issuer(bad)
        self.assertEqual(
            discovery_document("https://example.com/oidc")["jwks_uri"],
            "https://example.com/oidc/.well-known/jwks.json",
        )


def _run_cli(key_dir, out):
    env = {name: value for name, value in os.environ.items() if name != "ROOKRUNNER_KEY_DIR"}
    with tempfile.TemporaryDirectory(prefix="execution-oidc-state-") as state:
        return subprocess.run(
            [
                sys.executable,
                "-m",
                "execution_core",
                "--state",
                state,
                "oidc",
                "publish",
                "--issuer",
                ISSUER,
                "--out",
                str(out),
                "--key-dir",
                str(key_dir),
            ],
            capture_output=True,
            text=True,
            env=env,
        )


if __name__ == "__main__":
    unittest.main()

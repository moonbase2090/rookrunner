        self.assertNotIn("host.docker.internal:", stored)
        self.assertEqual(len(self.opened), 1)
        self.assertTrue(self.opened[0].closed)
        minted = [entry for entry in self.audit() if "jti" in entry]
        self.assertEqual([entry["jti"] for entry in minted], [claims["jti"]])
        self.assertEqual(minted[0]["step_index"], 0)


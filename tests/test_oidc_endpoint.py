    def tearDown(self):
        names = subprocess.run(
            ["docker", "ps", "-aq", "--filter", "name=rookrunner-"],
            capture_output=True,
            text=True,
        )
        for container in names.stdout.split():
            subprocess.run(["docker", "rm", "-f", container], capture_output=True)

    def _run(self, name, workflow, event, event_name, network="bridge", **settings):
        from execution_core.plan import plan_snapshot
        from execution_core.run import run_job
        from test_run import _capture

        root = self.state / name
        root.mkdir()
        repo, snapshot, digest, workspace = _capture(root, workflow)
        sha = subprocess.run(
            ["git", "-C", str(repo), "rev-parse", "HEAD"], capture_output=True, text=True
        ).stdout.strip()
        plan = plan_snapshot(snapshot, "build")["plan"]
        run = OidcRun(self.settings(**settings), run_id=f"run-{name}", attempt=1)
        opened = []

        class Recorded(JobListener):
            def __init__(self, *args, **kwargs):
                super().__init__(*args, **kwargs)
                opened.append(self)

        with mock.patch.object(run_module, "JobListener", Recorded):
            result = run_job(
                snapshot,
                digest,
                workspace,
                plan,
                self.image,
                event,
                event_name=event_name,
                network=network,
                oidc=run,
            )
        self.opened = opened
        return result, plan, workspace, sha


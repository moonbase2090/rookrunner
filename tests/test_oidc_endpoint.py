class GateTests(_Keyed):
    def test_only_an_explicit_id_token_write_grants_it(self):
        self.assertTrue(id_token_write_granted({"id-token": "write", "contents": "read"}))
        for permissions in (None, "read-all", {}, {"id-token": "read"}, {"id-token": "none"}):
            with self.subTest(permissions=permissions):
                self.assertFalse(id_token_write_granted(permissions))

    def _prepare(self, job, event=PUSH, event_name="push", network="bridge", **settings):
        runtime = _JobRuntime()
        failures = []
        run = OidcRun(self.settings(**settings), run_id="run-1", attempt=1)
        identity = {
            "workflow": "Deploy",
            "workflow_path": ".github/workflows/deploy.yml",
            "sha": SHA,
        }
        with mock.patch("execution_core.run._oidc_address", return_value="127.0.0.1"):
            ready = _prepare_oidc(
                runtime, run, job, {}, event, event_name, network, identity, (), failures.append
            )
        self.addCleanup(_close_oidc, runtime)
        return ready, runtime, failures

    def _env(self, runtime):
        step = {"run": "true", "env": {}}
        return dict(_merged_env({"env": {}}, {"env": {}}, step, runtime, "step-0", None))

    def test_a_granted_trusted_job_receives_both_names_on_every_step(self):
        ready, runtime, failures = self._prepare(
            {"id": "deploy", "permissions": {"id-token": "write"}, "steps": []}
        )
        self.assertTrue(ready)
        self.assertEqual(failures, [])
        env = self._env(runtime)
        self.assertEqual(env[REQUEST_URL_ENV], runtime.oidc.env()[REQUEST_URL_ENV])
        self.assertEqual(env[REQUEST_TOKEN_ENV], runtime.oidc.request_token)
        listener = runtime.oidc
        _close_oidc(runtime)
        self.assertIsNone(runtime.oidc)
        self.assertTrue(listener.closed)
        self.assertNotIn(REQUEST_URL_ENV, self._env(runtime))

    def test_no_contract_without_the_grant_or_for_a_refused_run(self):
        fork = json.loads(json.dumps(PULL))
        fork["pull_request"]["head"]["repo"] = {"id": 202}
        deleted = json.loads(json.dumps(PULL))
        deleted["pull_request"]["head"]["repo"] = None
        cases = [
            ({"permissions": "read-all"}, PUSH, "push", {}),
            ({}, PUSH, "push", {}),
            ({"permissions": {}}, PUSH, "push", {}),
            ({"permissions": {"id-token": "write"}}, fork, "pull_request", {"pull_requests": True}),
            (
                {"permissions": {"id-token": "write"}},
                deleted,
                "pull_request",
                {"pull_requests": True},
            ),
            ({"permissions": {"id-token": "write"}}, PULL, "pull_request", {}),
            ({"permissions": {"id-token": "write"}}, {"ref": "refs/heads/main"}, "push", {}),
        ]
        for job, event, event_name, settings in cases:
            with self.subTest(job=job, event_name=event_name, ref=event.get("ref")):
                ready, runtime, failures = self._prepare(
                    {"id": "deploy", "steps": [], **job}, event, event_name, **settings
                )
                self.assertTrue(ready)
                self.assertEqual(failures, [])
                self.assertIsNone(runtime.oidc)
                env = self._env(runtime)
                self.assertNotIn(REQUEST_URL_ENV, env)
                self.assertNotIn(REQUEST_TOKEN_ENV, env)

    def test_an_override_run_gets_no_contract_and_is_audited(self):
        runtime = _JobRuntime()
        run = OidcRun(self.settings(), run_id="run-2", attempt=1, untrusted_override=True)
        job = {"id": "deploy", "permissions": {"id-token": "write"}, "steps": []}
        identity = {"workflow": "Deploy", "workflow_path": ".github/workflows/d.yml", "sha": SHA}
        ready = _prepare_oidc(
            runtime, run, job, {}, PUSH, "push", "bridge", identity, (), self.fail
        )
        self.assertTrue(ready)
        self.assertIsNone(runtime.oidc)
        self.assertEqual(
            runtime.secret_notes,
            [
                "id-token: write did not receive a token request: "
                "run was started by an untrusted override"
            ],
        )
        self.assertEqual(self.audit()[0]["reason"], "run was started by an untrusted override")

    def test_a_none_network_fails_before_the_first_step(self):
        ready, runtime, failures = self._prepare(
            {"id": "deploy", "permissions": {"id-token": "write"}, "steps": []}, network="none"
        )
        self.assertFalse(ready)
        self.assertEqual(failures, [NETWORK_MESSAGE])
        self.assertIn("--network bridge", NETWORK_MESSAGE)
        self.assertIsNone(runtime.oidc)


class PlanTests(unittest.TestCase):
    def test_id_token_write_is_accepted_and_every_other_write_is_not(self):
        for prefix, body in (
            ("permissions:\n  id-token: write\n", ""),
            ("", "    permissions:\n      id-token: write\n      contents: read\n"),
        ):
            workflow = (
                f"{prefix}on: push\njobs:\n  build:\n{body}    steps:\n      - run: echo hi\n"
            )
            plan = plan_workflow(workflow.encode(), "build")["plan"]
            recorded = plan["workflow"].get("permissions") or plan["job"]["permissions"]
            self.assertEqual(recorded["id-token"], "write")
            self.assertEqual(plan["capability_version"], 12)
        for scope in ("contents", "actions", "packages", "pull-requests"):
            workflow = (
                f"permissions:\n  {scope}: write\non: push\njobs:\n  build:\n"
                "    steps:\n      - run: echo hi\n"
            )
            with self.subTest(scope=scope), self.assertRaises(PlanError) as caught:
                plan_workflow(workflow.encode(), "build")
            self.assertEqual(caught.exception.kind, "CAPABILITY_UNSUPPORTED")
            self.assertEqual(caught.exception.field, f"permissions.{scope}")

    def test_a_step_cannot_set_the_contract_names(self):
        for name in (REQUEST_URL_ENV, REQUEST_TOKEN_ENV):
            workflow = (
                "on: push\njobs:\n  build:\n    steps:\n"
                f"      - run: echo hi\n        env:\n          {name}: x\n"
            )
            with self.subTest(name=name), self.assertRaises(PlanError) as caught:
                plan_workflow(workflow.encode(), "build")
            self.assertEqual(caught.exception.field, f"jobs.build.steps.0.env.{name}")
            self.assertIn(name, str(caught.exception))



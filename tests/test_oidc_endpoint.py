def _install_key(key_dir):
    """Generate one key with openssl and install it as oidc/<kid>.pem and active."""

    oidc = Path(key_dir) / "oidc"
    oidc.mkdir(parents=True)
    os.chmod(key_dir, 0o700)
    os.chmod(oidc, 0o700)
    generated = Path(key_dir) / "generated.pem"
    subprocess.run(
        [
            "openssl",
            "genpkey",
            "-algorithm",
            "RSA",
            "-pkeyopt",
            "rsa_keygen_bits:2048",
            "-out",
            str(generated),
        ],
        check=True,
        capture_output=True,
    )
    kid = OidcKey(*_load_rsa_key(generated.read_bytes())).kid
    target = oidc / f"{kid}.pem"
    generated.rename(target)
    os.chmod(target, 0o600)
    (oidc / "active").write_text(kid + "\n")
    os.chmod(oidc / "active", 0o600)
    return kid


def _decode(segment):
    return json.loads(base64.urlsafe_b64decode(segment + "=" * (-len(segment) % 4)))


def _get(url, token=None, method="GET"):
    request = urllib.request.Request(url, method=method)
    if token is not None:
        request.add_header("Authorization", f"Bearer {token}")
    try:
        with urllib.request.urlopen(request, timeout=5) as response:
            return response.status, json.loads(response.read())
    except urllib.error.HTTPError as error:
        return error.code, json.loads(error.read())


def _core_get_id_token(env, audience):
    """What @actions/core getIDToken sends: the URL plus &audience=, and a bearer token."""

    url = env[REQUEST_URL_ENV] + "&audience=" + urllib.parse.quote(audience, safe="")
    return _get(url, env[REQUEST_TOKEN_ENV])


class _Keyed(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.keys = tempfile.TemporaryDirectory(prefix="execution-oidc-endpoint-")
        root = Path(cls.keys.name).resolve()
        cls.key_dir = root / "keys"
        cls.kid = _install_key(cls.key_dir)
        cls.key_set = load_key_set(str(cls.key_dir))
        cls.jwks = cls.key_set.jwks()

    @classmethod
    def tearDownClass(cls):
        cls.keys.cleanup()

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory(prefix="execution-test-")
        self.addCleanup(self.tmp.cleanup)
        self.state = Path(self.tmp.name).resolve()

    def settings(self, **extra):
        return OidcSettings(
            ISSUER, self.key_set, repository=REPOSITORY, state_dir=self.state, **extra
        )

    def audit(self):
        path = self.state / AUDIT_FILE
        if not path.exists():
            return []
        return [json.loads(line) for line in path.read_text().splitlines()]


class ListenerTests(_Keyed):
    def listener(self, masks=None, event=PUSH, event_name="push"):
        run = OidcRun(self.settings(), run_id="run-1", attempt=1)
        listener = JobListener(
            run,
            job_id="deploy",
            event=event,
            event_name=event_name,
            sha=SHA,
            workflow="Deploy",
            workflow_path=".github/workflows/deploy.yml",
            masks=MaskList() if masks is None else masks,
            address="127.0.0.1",
        )
        self.addCleanup(listener.close)
        listener.step_index = 3
        return listener

    def test_a_core_style_request_gets_a_signed_token_with_the_run_claims(self):
        masks = MaskList()
        listener = self.listener(masks)
        env = listener.env()
        self.assertRegex(
            env[REQUEST_URL_ENV], r"^http://host\.docker\.internal:\d+/token\?job=[\w-]{22}$"
        )
        self.assertEqual(len(base64.urlsafe_b64decode(env[REQUEST_TOKEN_ENV] + "=")), 32)
        local = {
            REQUEST_URL_ENV: env[REQUEST_URL_ENV].replace("host.docker.internal", "127.0.0.1"),
            REQUEST_TOKEN_ENV: env[REQUEST_TOKEN_ENV],
        }
        code, body = _core_get_id_token(local, "api://AzureADTokenExchange")
        self.assertEqual(code, 200)
        self.assertEqual(set(body), {"value"})
        token = body["value"]
        header, payload, _ = token.split(".")
        self.assertEqual(_decode(header), {"alg": "RS256", "typ": "JWT", "kid": self.kid})
        claims = _decode(payload)
        self.assertEqual(claims["iss"], ISSUER)
        self.assertEqual(claims["aud"], "api://AzureADTokenExchange")
        self.assertEqual(claims["sub"], "repo:octo-org/octo-repo:ref:refs/heads/main")
        self.assertEqual(claims["repository"], REPOSITORY)
        self.assertEqual(claims["sha"], SHA)
        self.assertEqual(claims["run_id"], "run-1")
        self.assertEqual(claims["run_attempt"], "1")
        self.assertEqual(claims["exp"] - claims["iat"], 300)
        self.assertTrue(_rs256_verifies(self.jwks["keys"][0], token))

        self.assertIn(token, masks)
        self.assertIn(token, masks.secrets)
        self.assertIn(env[REQUEST_TOKEN_ENV], masks.secrets)
        self.assertEqual(
            listener.drain_notes(),
            [
                "oidc token minted for aud api://AzureADTokenExchange "
                "sub repo:octo-org/octo-repo:ref:refs/heads/main"
            ],
        )
        self.assertEqual(listener.drain_notes(), [])

        audit_path = self.state / AUDIT_FILE
        self.assertEqual(stat.S_IMODE(audit_path.stat().st_mode), 0o600)
        text = audit_path.read_text()
        self.assertNotIn(token, text)
        self.assertNotIn(env[REQUEST_TOKEN_ENV], text)
        [entry] = self.audit()
        self.assertEqual(entry["run_id"], "run-1")
        self.assertEqual(entry["attempt"], "1")
        self.assertEqual(entry["job_id"], "deploy")
        self.assertEqual(entry["step_index"], 3)
        self.assertEqual(entry["aud"], "api://AzureADTokenExchange")
        self.assertEqual(entry["sub"], claims["sub"])
        self.assertEqual(entry["jti"], claims["jti"])
        self.assertEqual(entry["kid"], self.kid)
        self.assertEqual(entry["exp"], claims["exp"])
        self.assertNotIn("reason", entry)

    def test_refusals_carry_no_token_and_are_audited(self):
        listener = self.listener()
        env = listener.env()
        base = env[REQUEST_URL_ENV].replace("host.docker.internal", "127.0.0.1")
        good = env[REQUEST_TOKEN_ENV]
        port = listener.port
        cases = [
            (base + "&audience=sts.amazonaws.com", "wrong", 401),
            (base + "&audience=sts.amazonaws.com", None, 401),
            (base, good, 400),
            (base + "&audience=", good, 400),
            (base + "&audience=a&audience=b", good, 400),
            (base + "&audience=" + "x" * 257, good, 400),
            (base + "&audience=sts%20amazonaws", good, 400),
            (
                f"http://127.0.0.1:{port}/token?job=unknown&audience=sts.amazonaws.com",
                good,
                401,
            ),
            (f"http://127.0.0.1:{port}/other?" + base.split("?", 1)[1] + "&audience=x", good, 401),
        ]
        for url, token, expected in cases:
            with self.subTest(url=url.split("?", 1)[1], token=token):
                code, body = _get(url, token)
                self.assertEqual(code, expected)
                self.assertNotIn("value", body)
                self.assertNotRegex(json.dumps(body), JWT)
        code, body = _get(base + "&audience=sts.amazonaws.com", good, method="POST")
        self.assertEqual(code, 405)
        self.assertEqual(listener.drain_notes(), [])
        reasons = [entry.get("reason") for entry in self.audit()]
        self.assertEqual(len(reasons), len(cases))
        self.assertTrue(all(reasons))
        self.assertIn("request token is not accepted", reasons)
        self.assertIn("job is unknown or finished", reasons)
        self.assertIn("audience is required once", reasons)

    def test_a_finished_job_is_refused(self):
        listener = self.listener()
        env = listener.env()
        url = env[REQUEST_URL_ENV].replace("host.docker.internal", "127.0.0.1")
        listener.close()
        with self.assertRaises(urllib.error.URLError):
            _get(url + "&audience=sts.amazonaws.com", env[REQUEST_TOKEN_ENV])
        code, body = listener.answer(
            "/token?job=" + listener.opaque + "&audience=sts.amazonaws.com",
            f"Bearer {env[REQUEST_TOKEN_ENV]}",
        )
        self.assertEqual(code, 401)
        self.assertEqual(body, {"message": "job is unknown or finished"})

    def test_a_job_gets_at_most_60_tokens(self):
        listener = self.listener()
        bearer = f"Bearer {listener.request_token}"
        path = f"/token?job={listener.opaque}&audience=sts.amazonaws.com"
        codes = [listener.answer(path, bearer)[0] for _ in range(MAX_REQUESTS + 1)]
        self.assertEqual(codes[:MAX_REQUESTS], [200] * MAX_REQUESTS)
        self.assertEqual(codes[MAX_REQUESTS], 429)

    def test_a_failed_audit_log_issues_no_token(self):
        masks = MaskList()
        listener = self.listener(masks)
        with (
            mock.patch.object(listener.run.settings.audit, "append", return_value=False),
            mock.patch(
                "execution_core.oidc_endpoint.mint",
                side_effect=AssertionError("mint must not run without an audit record"),
            ),
        ):
            code, body = listener.answer(
                f"/token?job={listener.opaque}&audience=sts.amazonaws.com",
                f"Bearer {listener.request_token}",
            )
        self.assertEqual(code, 500)
        self.assertNotIn("value", body)
        self.assertNotRegex(json.dumps(body), JWT)
        self.assertEqual(listener.drain_notes(), [])
        self.assertEqual(list(masks.secrets), [listener.request_token])

    def test_a_same_repository_pull_request_gets_the_pull_request_subject(self):
        listener = self.listener(event=PULL, event_name="pull_request")
        code, body = listener.answer(
            f"/token?job={listener.opaque}&audience=sts.amazonaws.com",
            f"Bearer {listener.request_token}",
        )
        self.assertEqual(code, 200)
        self.assertEqual(
            _decode(body["value"].split(".")[1])["sub"], "repo:octo-org/octo-repo:pull_request"
        )


